# Stage 2: Operators

# Arithmetic operators
x = 10
y = 3

print("Addition:", x + y)
print("Subtraction:", x - y)
print("Multiplication:", x * y)
print("Division:", x / y)
print("Modulus:", x % y)
print("Exponent:", x ** y)
print("Floor division:", x // y)

# Comparison operators
print("Equal:", x == y)
print("Not equal:", x != y)
print("Greater:", x > y)
print("Less:", x < y)

# Logical operators
age = 20
has_id = True
print("Adult and has ID:", age >= 18 and has_id)
print("Adult or has ID:", age < 18 or has_id)
print("Not has_id:", not has_id)

# Assignment operators
value = 5
value += 2
value *= 3
print("Final value:", value)
