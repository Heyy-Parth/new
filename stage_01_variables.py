# Stage 1: Variables

# Variable assignment
name = "Alice"
age = 25
height = 5.8
is_student = True

print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Is student:", is_student)

# Reassigning variables
name = "Bob"
print("Updated name:", name)

# Different data types
integer_value = 10
float_value = 3.14
string_value = "Python"
boolean_value = False

print(type(integer_value))
print(type(float_value))
print(type(string_value))
print(type(boolean_value))

# Type conversion
num_string = "42"
number = int(num_string)
print("Converted number:", number)
print("String version:", str(number))
